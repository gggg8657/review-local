def _run(text, b=False, i=False, color=None):
    rpr = ("<w:b/>" if b else "") + ("<w:i/>" if i else "") + (f'<w:color w:val="{color}"/>' if color else "")
    return f'<w:r>{"<w:rPr>" + rpr + "</w:rPr>" if rpr else ""}<w:t xml:space="preserve">{escape(text)}</w:t></w:r>'


def _p(runs, style=None, ind=0):
    ppr = (f'<w:pStyle w:val="{style}"/>' if style else "") + (f'<w:ind w:left="{ind}"/>' if ind else "")
    if isinstance(runs, str):
        runs = _run(runs)
    return f'<w:p>{"<w:pPr>" + ppr + "</w:pPr>" if ppr else ""}{runs}</w:p>'


def to_docx(rec):
    secs, lab = sections(rec)
    body = []
    for kind, x in secs:
        if kind == "h1":
            body.append(_p(x, "Title"))
        elif kind == "h2":
            body.append(_p(x, "Heading1"))
        elif kind == "meta":
            body += [_p(_run(f"{k}: ", b=True) + _run(str(v))) for k, v in x if v]
        elif kind == "note":
            body.append(_p(x, "Note"))
        elif kind == "p":
            body.append(_p(x))
        elif kind in ("ol", "ul"):
            body += [_p(f"{n}. {t}" if kind == "ol" else f"• {t}", ind=240) for n, t in enumerate(x, 1)]
        elif kind == "issue":
            body.append(_p(f"{x['id']}. {x.get('title') or x['cat']}  [{x['cat']}]", "Heading2"))
            body.append(_p(_run(f"{lab['where']}: {x.get('where') or '-'}" + "".join(f" · {a['where']}" for a in x.get("also") or []), i=True, color="6B7280")))
            if x.get("quote"):
                body.append(_p(x["quote"], "Quote"))
            body.append(_p(_run(f"{lab['why']}: ", b=True) + _run(x["why"])))
            if x.get("fix"):
                body.append(_p(_run(f"{lab['fix']}: ", b=True) + _run(x["fix"])))
        elif kind == "rule":
            col = {"major": "B42318", "info": "6B7280"}.get(x["sev"])
            body.append(_p(_run(f"• {x['title']} ", b=True, color=col) + _run(f"({x.get('where') or '-'}) — {x['why']}" + (f" → {x['fix']}" if x.get("fix") else "")), ind=120))
            if x.get("quote"):
                body.append(_p(x["quote"][:220], "Quote"))
        elif kind == "qa":
            for n, q in enumerate(x, 1):
                body.append(_p(_run(f"{n}. {q['q']}", b=True)))
                if q.get("tip"):
                    body.append(_p(_run(f"{lab['tip']}: ", i=True) + _run(q["tip"]), ind=240))
    doc = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
           f'<w:body>{"".join(body)}<w:sectPr><w:pgSz w:w="11906" w:h="16838"/><w:pgMar w:top="1300" w:right="1200" w:bottom="1300" w:left="1200" w:header="600" w:footer="600" w:gutter="0"/></w:sectPr></w:body></w:document>')
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    core = ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?><cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" '
            'xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:dcterms="http://purl.org/dc/terms/" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">'
            f'<dc:title>{escape(lab["title"])}</dc:title><dc:creator>review-local</dc:creator>'
            f'<dcterms:created xsi:type="dcterms:W3CDTF">{now}</dcterms:created></cp:coreProperties>')
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", CT)
        z.writestr("_rels/.rels", RELS)
        z.writestr("word/_rels/document.xml.rels", DOC_RELS)
        z.writestr("word/document.xml", doc)
        z.writestr("word/styles.xml", STYLES)
        z.writestr("docProps/core.xml", core)
    return buf.getvalue()
