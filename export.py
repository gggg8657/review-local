SEV_ORDER = {"major": 0, "minor": 1, "info": 2}


def _lab(rec):
    return L["en" if (rec.get("review") or {}).get("lang") == "en" else "ko"]


def sections(rec):
    """공통 구조: [(kind, payload)] — md/txt/docx 가 같은 내용을 쓴다"""
    lab, doc, rv = _lab(rec), rec["doc"], rec.get("review") or {}
    opt = rv.get("options") or rec.get("options") or {}
    out = [("h1", f"{lab['title']} — {doc.get('title') or doc.get('name')}"),
           ("meta", [(lab["file"], doc.get("name", "")), (lab["date"], rv.get("ts") or rec.get("ts", "")), (lab["model"], rv.get("model", "")),
                     (lab["journal"], opt.get("journal") or "-"), (lab["type"], opt.get("mtype") or "-"), (lab["depth"], opt.get("depth") or "-")]),
           ("note", lab["note"])]
    if not rv:
        out.append(("p", lab["nollm"]))
    else:
        out.append(("h2", lab["summary"]))
        out.append(("ol", rv.get("summary", {}).get("contrib") or [lab["none"]]))
        v = rv.get("verdict") or {}
        out.append(("h2", f"{lab['verdict']}: {v.get('label') or '-'}"))
        out.append(("ul", [r["text"] for r in v.get("reasons") or []]))
    issues = rec.get("issues") or []
    llm = [i for i in issues if i["src"] == "llm"]
    for sev, key in (("major", "major"), ("minor", "minor")):
        if not rv:
            break
        items = [i for i in llm if i["sev"] == sev]
        out.append(("h2", lab[key]))
        if not items:
            out.append(("p", lab["none"]))
        for i in items:
            out.append(("issue", i))
    rule = sorted([i for i in issues if i["src"] == "rule"], key=lambda i: (SEV_ORDER.get(i["sev"], 3), i["cat"], i["pos"]))
    out.append(("h2", lab["rule"]))
    if not rule:
        out.append(("p", lab["none"]))
    for i in rule:
        out.append(("rule", i))
    if rv and rv.get("questions"):
        out.append(("h2", lab["questions"]))
        out.append(("qa", rv["questions"]))
    return out, lab


def to_md(rec):
    secs, lab = sections(rec)
    o = []
    for kind, x in secs:
        if kind == "h1":
            o.append(f"# {x}\n")
        elif kind == "h2":
            o.append(f"\n## {x}\n")
        elif kind == "meta":
            o += [f"- **{k}**: {v}" for k, v in x if v]
        elif kind == "note":
            o.append(f"\n> {x}\n")
        elif kind == "p":
            o.append(x)
        elif kind == "ol":
            o += [f"{n}. {t}" for n, t in enumerate(x, 1)]
        elif kind == "ul":
            o += [f"- {t}" for t in x]
        elif kind == "issue":
            o.append(f"### {x['id']}. {x.get('title') or x['cat']}  `{x['cat']}`")
            o.append(f"*{lab['where']}: {x.get('where') or '-'}" + "".join(f" · {a['where']}" for a in x.get("also") or []) + "*\n")
            if x.get("quote"):
                o.append(f"> {x['quote']}\n")
            o.append(f"- **{lab['why']}**: {x['why']}")
            if x.get("fix"):
                o.append(f"- **{lab['fix']}**: {x['fix']}")
            o.append("")
        elif kind == "rule":
            tag = {"major": "**[major]** ", "minor": "", "info": f"[{lab['info']}] "}.get(x["sev"], "")
            o.append(f"- {tag}**{x['title']}** ({x.get('where') or '-'}) — {x['why']}" + (f" → {x['fix']}" if x.get("fix") else ""))
            if x.get("quote"):
                o.append(f"  > {x['quote'][:220]}")
        elif kind == "qa":
            for n, q in enumerate(x, 1):
                o.append(f"{n}. **{q['q']}**")
                if q.get("tip"):
                    o.append(f"   - {lab['tip']}: {q['tip']}")
    return "\n".join(o).strip() + "\n"


def to_txt(rec):
    md = to_md(rec)
    md = re.sub(r"^#+\s*", "", md, flags=re.M)
    md = re.sub(r"\*\*(.+?)\*\*", r"\1", md)
    md = re.sub(r"(?<!\w)\*(.+?)\*(?!\w)", r"\1", md)
    return md.replace("`", "")


